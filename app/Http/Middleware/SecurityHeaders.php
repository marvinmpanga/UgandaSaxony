<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

class SecurityHeaders
{
    /**
     * Attach standard defensive HTTP security headers to all web responses.
     *
     * @param  Closure(Request): Response  $next
     */
    public function handle(Request $request, Closure $next): Response
    {
        $response = $next($request);

        $response->headers->set('X-Content-Type-Options', 'nosniff');
        $response->headers->set('X-Frame-Options', 'SAMEORIGIN');
        $response->headers->set('Referrer-Policy', 'strict-origin-when-cross-origin');
        $response->headers->set('Permissions-Policy', 'camera=(), microphone=(), geolocation=()');

        if (! $response->headers->has('Content-Security-Policy')) {
            $response->headers->set('Content-Security-Policy', $this->buildCsp($request));
        }

        if ($request->isSecure()) {
            $response->headers->set('Strict-Transport-Security', 'max-age=31536000; includeSubDomains');
        }

        return $response;
    }

    private function buildCsp(Request $request): string
    {
        $isLocal = app()->environment('local');
        $isAdmin = $request->is('admin') || $request->is('admin/*') || $request->is('livewire/*');

        $scriptSrc = ["'self'", "'unsafe-inline'"];
        $connectSrc = ["'self'"];
        $styleSrc = ["'self'", "'unsafe-inline'", 'https://fonts.googleapis.com'];

        if ($isAdmin) {
            // Filament / Alpine.js requires unsafe-eval for reactive expressions
            $scriptSrc[] = "'unsafe-eval'";
        }

        if ($isLocal && is_file(public_path('hot'))) {
            // Chromium CSP host-source does not match IPv6 literals like http://[::1]:5173
            // generated by Vite's hot file, so allow local http/ws dev-server schemes only
            // when running in local HMR mode.
            $scriptSrc[] = 'http:';
            $styleSrc[] = 'http:';
            $connectSrc[] = 'http:';
            $connectSrc[] = 'ws:';
        }

        return implode('; ', [
            "default-src 'self'",
            "base-uri 'self'",
            "object-src 'none'",
            "frame-ancestors 'self'",
            "form-action 'self'",
            "img-src 'self' data: blob: https:",
            "font-src 'self' data: https://fonts.gstatic.com",
            'style-src '.implode(' ', $styleSrc),
            'script-src '.implode(' ', $scriptSrc),
            'connect-src '.implode(' ', $connectSrc),
        ]);
    }
}
